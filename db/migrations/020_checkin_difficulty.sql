-- ===== 20/21 打卡的难度 =====
--
-- 难度是**出题参数**，不是题目属性：一道题事后看不出它当初是「基础」还是
-- 「提高」（同样考有理数，`(-3)+5` 是基础，`(-3)^2-5×(-2)` 就能算提高）。
-- 所以它必须随打卡一起存下来，否则家长回头看「我今天给她出的是提高」
-- 这件事就永远查不到了，只能凭记忆。
--
-- 默认值留给「学生自己发起」那条路：自动从错题聚合出来的题不指定难度，
-- 空串表示「没要求」而不是「基础」—— 后者会让统计里凭空多出一批基础题。
ALTER TABLE checkin_quiz ADD COLUMN IF NOT EXISTS difficulty TEXT NOT NULL DEFAULT '';

COMMENT ON COLUMN checkin_quiz.difficulty IS
  '家长发起时的难度要求：基础 / 提高 / 挑战；学生自发起或未指定时为空串。';
