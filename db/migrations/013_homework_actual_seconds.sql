-- 作业的实际用时（秒）。
--
-- 客户端新增了「专注计时」：打开计时页才开始累计，暂停时冻结，
-- 结束时把 `原有 + 本次` 整份写回这一列。
--
-- ## 为什么是秒，不是分钟
--
-- 计时界面按秒走。按分钟存的话，59 秒会落成 0 分钟，「用了 0 分钟」
-- 在界面上和「还没计时」长得一模一样。`estimated_minutes` 是计划值，
-- 带小数无所谓；实际值是测量值，整数秒已经足够精确。
--
-- ## 为什么默认 0 且不回填
--
-- 0 = 从来没计过时。这个版本之前没有任何计时记录，用
-- `estimated_minutes * 60` 回填等于伪造一份「孩子实际用了多久」的数据，
-- 而这份数字会进家长端与学习报告 —— 假数据比空着坏得多。
--
-- `IF NOT EXISTS` 让这条迁移可以重跑：客户端本地库那条迁移也做了同样的
-- 列判断，两侧都按「可重入」写。
ALTER TABLE homework
  ADD COLUMN IF NOT EXISTS actual_seconds INTEGER NOT NULL DEFAULT 0;
