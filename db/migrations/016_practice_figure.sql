-- 变式题的配图。
--
-- ## 为什么不是存图片
--
-- 存的是「点和线」的结构化描述（点坐标、多边形、尺寸标注），由客户端画出来。
-- 模型不能画图：图像生成模型画的几何图，线长与标注数字对不上 —— 图上标着
-- `a` 的边可能是任意长度，写着 50° 的角可能是 80°。那种图看起来完全正常，
-- 学生照着它推理就会得出基于错误前提的结论，而且没有任何报错。
--
-- ## 为什么允许 NULL
--
-- 绝大多数变式题不需要图（计算、方程、应用题）。给一个 `'{}'` 默认值会让
-- 「这道题有没有图」变成必须解析才知道，而 `figure_json IS NULL` 能直接
-- 数出「有多少道题带图」—— 这个数字是判断「读原题出图」这条链路
-- 到底有没有在工作时最直接的依据。
--
-- 历史数据全部为 NULL，与「没有图」的既有表现完全一致，不需要回填。
ALTER TABLE ai_practice_question
  ADD COLUMN IF NOT EXISTS figure_json TEXT;
