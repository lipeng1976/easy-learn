import '../services/ai_data_source.dart';

/// 批改结果的**体检**：三条「模型说了话，可这句话本身站不住」的口径。
///
/// 抽出来的理由和 [HomeworkFeedbackText] 一样：这三条以前散在网络层与控制器
/// 各自的分支里，`test/` 下**一条覆盖都没有** —— 改坏了不会有任何东西变红。
/// 而它们的代价也不是「界面不好看」：
///
/// | 判据 | 不处理的后果 |
/// |---|---|
/// | [isUnreadable] | **一张拍空的照片 = 作业完成 + 满分 + 加分 + 家长收到「全对」** |
/// | [contradiction] | 一份自相矛盾的结果（错题 0 道、却扣了 20 分）被当成正常结果落库 |
/// | [isRetracted] | 模型自己在错因里写「此条不构成错误」的那条，照样变成要重做的错题 |
///
/// 前两条出自 `doc/open-items.md` B29 的实测：现网批改档（视觉）对纯白页面
/// **6 次里 3 次**回 `score:100 / items:[]`，而 `score:100 / items:[]` 恰好是
/// 「一次批改把错题库清空」的**正常路径**（`student_controller` 里先删后插）。
///
/// ⚠️ 三条都**只认文字**，因为模型到现在也只给文字。这不是理想形态 ——
/// 理想形态是让契约里有一个必填的 `readable` 字段（见 B29 的后续项）。
/// 在契约改掉之前，这里至少把「判断只此一处」和「可被测试盯住」两件事做到。
class GradingSanity {
  const GradingSanity._();

  /// 判定「这张照片没批成」的短语表。
  ///
  /// ⚠️ 这是**语义定义**，只许在这里出现一处 —— 控制器里、界面上都不许再写
  /// 第二份判断。本项目的头号 bug 类型就是同一件事有两份定义，然后慢慢漂开。
  ///
  /// 只收**对整张照片下的结论**，不收修饰词：
  ///
  /// - 「空白」「照片为空」「没有拍到」「未拍到」「没有作业内容」—— 画面里没有
  ///   可批改的东西；
  /// - 「不是作业」—— 拍的压根不是作业；
  /// - 「无法批改」「无法识别」「无法辨认」「未检测到」—— 它明说读不出来；
  /// - 「请重新拍照」「请重拍」—— 模型自己就叫学生重拍，那它显然没批成。
  ///
  /// ⚠️ 刻意**不收「模糊」「不清晰」**：它们是修饰，可以出现在
  /// 「有几处笔迹模糊，但整体全部正确」这种**真的全对**的总结里，
  /// 收进来会把真结果误判成不可读。而实测到的三句原文
  /// （「照片是空白的……无法批改」／「作业照片为空，按满分处理」／「无法批改」）
  /// 全部落在上面这组词里 ⇒ **不需要**那些有误伤风险的词。
  ///
  /// 宁可漏、不可误伤：误伤一次 = 一个全对的孩子被判成需要重拍；
  /// 漏一次 = 错题库被清空 + 白送一次「全对」加分。
  static const List<String> unreadableMarkers = [
    '空白',
    '照片为空',
    '没有拍到',
    '未拍到',
    '没有作业内容',
    '不是作业',
    '无法批改',
    '无法识别',
    '无法辨认',
    '未检测到',
    '请重新拍照',
    '请重拍',
  ];

  /// 判定「模型在错因里当场反悔」的短语表。
  ///
  /// 实测到的三句原文（`doc/open-items.md` B29 的 E 第三条）：
  ///
  /// - 「……（复核：结果为 -1 与标准答案一致，**此条实际不构成错误，请勿计入错题库**）」
  /// - 「经核对，学生填的 D 与标准答案一致，**此条为误判**，请以「无错题」处理」
  /// - 「**等等，让我重新算一下。哎呀，学生算的是对的！**」
  ///
  /// 这些字符串**照样入库**，就变成了一道要重做的「错题」。所以入库前拦一道。
  ///
  /// ⚠️ 只收**明确指向本条的撤回语**，不收「不是错误」这种半截短语 ——
  /// 「这道题的错因不是错误地通分，而是……」会误命中，把一条**真错题**丢掉。
  static const List<String> retractedMarkers = [
    '不构成错误',
    '勿计入错题库',
    '不计入错题库',
    '此条为误判',
    '属于误判',
    '其实做对了',
    '实际做对了',
    '学生做对了',
    '学生算的是对的',
    '学生填的是对的',
    '按无错题处理',
    '按「无错题」处理',
    '不应判错',
    // 2026-10-21 实测补的两条（`qwen3.5-omni-plus`，同一张照片）：
    // 「此处经复核，学生答案正确（…），不应判错。**此条目为误报**，请忽略。」
    // —— 那次恰好含「不应判错」才被拦住，换一句「此条为误报」就漏了。
    // 只收「为误报」而不收裸的「误报」：后者可能出现在
    // 「把误报率从 3% 降到 1%」这种**真的在讲误报**的错因里。
    '为误报',
    '请忽略',
  ];

  /// 照片根本没法批改 —— 这不是「全对」。
  ///
  /// 两个条件缺一不可：
  /// 1. `summary` 里出现 [unreadableMarkers]；
  /// 2. **`items` 是空的**。
  ///
  /// 第 2 条是这条判据的安全阀：只要报出了任何一条错题，就说明它**读得出来**，
  /// 那次批改是真做过的 —— 哪怕总结里带了一句「部分区域看不清」。
  /// 而真正会造成破坏的分支（清空错题库、发「全对」加分）本来就只挂在
  /// 「一条错题都没有」上，所以拦在这里刚好覆盖全部危险路径，不多不少。
  ///
  /// ⚠️ **不看 `score`**：实测 `qwen3.8-max` / `flash` 对白页回的是
  /// 「无法批改」+ `score:0` —— 那份结果同样一条错题都没有，
  /// 落到下面照样会把作业置成「已完成」、发出「《X》全对」的加分通知
  /// （文案还配着 `得分 0`）。要求 `score == 100` 会把这一档全漏掉。
  static bool isUnreadable(HomeworkCheckOutcome outcome) {
    if (outcome.items.isNotEmpty) return false;
    final summary = outcome.summary;
    for (final marker in unreadableMarkers) {
      if (summary.contains(marker)) return true;
    }
    return false;
  }

  /// 错因已经自己反悔的条目：不该进错题库。
  static bool isRetracted(String wrongReason) {
    for (final marker in retractedMarkers) {
      if (wrongReason.contains(marker)) return true;
    }
    return false;
  }

  /// 把一批错题里「已经反悔」的挑出去，返回留下的那些。
  ///
  /// 单独给一个列表级的入口，是为了让调用点不必自己写 for —— 少一处
  /// 「忘了过滤」的可能。顺序保持原样：错题的展示顺序是模型给的优先级。
  static List<HomeworkCheckItem> withoutRetracted(List<HomeworkCheckItem> items) {
    return [
      for (final item in items)
        if (!isRetracted(item.wrongReason)) item,
    ];
  }

  /// `items` 空却扣了分 —— 自相矛盾，返回给 `validate` 的说明；不矛盾时返回 `null`。
  ///
  /// 契约自己推得出来：`score` **只由「做错了没有」决定**
  /// （见 `Schemas.homeworkCheck` 里 `score` 的说明）。那么
  /// 「`items` 为空」= 没有错题 = 不该扣分 ⇒ **`score` 必须是 100**。
  ///
  /// 现网实测：三次批改**每次都**返回「`items` 空、`score` 80」
  /// 而 `summary` 写着「共有 2 处计算错误」—— 模型知道有两处，只是没写进 `items`。
  /// 这种结果落库之后，界面上是「错题 0 道、得分 80」，两边再也对不上。
  ///
  /// 返回的字符串会被客户端当作 `retryHint` 发回服务端、拼进提示词
  /// （`prompts.js` 的 `systemPromptFor`），让模型重出一次 —— 这条链路现成，
  /// **服务端与提示词一个字都不用改**。
  static String? contradiction(HomeworkCheckOutcome outcome) {
    if (outcome.items.isEmpty && outcome.score != 100) {
      return 'items 为空表示没有错题，此时 score 必须是 100，'
          '你给的是 ${outcome.score}，两者矛盾。'
          '如果确实有做错的题，请把每一道都写进 items'
          '（含 knowledgePoint / originalAnswer / wrongReason）；'
          '如果没有做错的题，score 请写 100。';
    }
    return null;
  }

  /// 不可读时给学生的说法。
  ///
  /// 与「真的全对」必须**一眼分得开**：两者都会让作业变成终态，
  /// 但一个要说「请重拍」、一个要说「全对」。混成一句，学生就再也
  /// 不知道自己该不该重拍。
  static const String unreadableMessage =
      '照片看不清或没有拍到题目，这次没能批改。请重拍一张再提交。';

  /// 因为模型自己反悔而被丢掉的那几条，怎么跟学生说。
  ///
  /// 说出来的必要性：不说的话，学生看到「有 3 道错题已加入错题本」
  /// 却发现错题本里只多了 2 道，第一反应是「系统出错了」。
  static String retractedNote(int count) =>
      '另有 $count 条批改说明在复核后自行收回，未计入错题。';
}
