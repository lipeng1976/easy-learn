/// 演示种子数据的**唯一开关**。
///
/// ## 为什么默认关
///
/// `LocalDatabaseService.seedIfEmpty()` 会在**新库首次打开**时写入一批演示账号
/// （林小宇 / 林小桐 / 家长王老师）、结伴关系和演示作业、错题、积分流水；
/// 更隐蔽的是 `findUserByPhone` / `findUserByWechat` / `findUserById` 三个读方法
/// 也会**按需补写**同一批账号 —— 于是「演示数据是否完整」被绑在了
/// 「谁先发起一次用户查询」上。
///
/// 对真实用户来说这两条路的后果是一样的：**第一次打开就看到「别人的孩子」**，
/// 而且那些行是**真的写进库里的**，不是界面临时造的。用户会以为账号被盗用，
/// 或者以为自己的孩子被绑到了别人的家长名下 —— 这类问题排查起来很像数据串了，
/// 其实只是种子没关。
///
/// ## 为什么默认关而不是默认开
///
/// 默认关的失败形态是**看得见**的：演示环境忘了带参数 → 首屏列表是空的，
/// 一眼就能发现「这批数据没灌进来」。
/// 反过来默认开的失败形态是**静默的**：真实用户看到别人的孩子，全程没有任何报错。
/// 这与 `AI_REQUIRE_AUTH` 是同一套取舍 —— **默认值要选「失败看得见」的那一侧**。
///
/// ## 怎么开
///
/// 演示环境在**编译期**打开：`--dart-define=SEED_DEMO_DATA=true`。
/// `dev-stack.mjs` 打印的客户端命令、Web 走查脚本与安卓部署手册都带上了它。
///
/// ⚠️ **只在这一处读环境变量**，别在别处再散第二份判断 ——
/// 两个判断会漂成「一处开、一处关」，而这种不一致的症状恰恰是「某些列表有演示数据、
/// 某些没有」，看起来像数据坏了。
///
/// ⚠️ 已经灌过演示数据的老库**不会**被清理：当前没有真实用户，
/// 已装的都是可重装的测试包，不值得为它写一段迁移。
class DemoSeed {
  const DemoSeed._();

  /// 是否允许写入演示种子数据。
  ///
  /// 测试若要演示数据，必须**显式**传 `seedIfEmpty(demoData: true)`
  /// （见 `test/helpers/db_test_helper.dart` 的 `setUpTestDatabase()`）——
  /// 不去改这个常量，也不去改它的默认值。
  static const bool enabled = bool.fromEnvironment('SEED_DEMO_DATA');
}
