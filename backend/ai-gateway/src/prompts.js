/**
 * 组装系统提示词。
 *
 * [retryHint] 是上一次校验失败的原因（由客户端回传）。
 * 例如「steps 至少要有 1 项，实际 0 项」——把这句话直接交给模型，
 * 第二次基本都能修好；不给的话它只会按同样的方式再错一遍。
 */
export function systemPromptFor(capability, { retryHint = '', degradedHint = '' } = {}) {
  const base = PROMPTS[capability];
  if (!base) throw new Error(`没有为能力 ${capability} 定义提示词`);

  const blocks = [SHARED_TONE, base];
  if (degradedHint) {
    blocks.push(`上一次调用失败的具体原因：${degradedHint}`);
  }
  if (retryHint) {
    blocks.push(
      [
        '【重要】你上一次的输出没有通过结构校验，问题如下：',
        retryHint,
        '请重新输出，务必修正上述问题。',
      ].join('\n'),
    );
  }
  return blocks.join('\n\n');
}
